"""Write the int8 model and its settings as C files for the Pico 2 W firmware."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from sanad.data.harmonize import ACC_LIMIT_G, FS
from sanad.data.windowing import POST, PRE
from sanad.export.to_tflite import Int8Model
from sanad.models.common import CHANNELS


def write_model_array(blob: bytes, out_dir: Path, name: str = "sanad_model") -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = [", ".join(f"0x{b:02x}" for b in blob[i : i + 12]) for i in range(0, len(blob), 12)]
    cc = out_dir / f"{name}_data.cc"
    h = out_dir / f"{name}_data.h"
    cc.write_text(
        f'#include "{name}_data.h"\n\n'
        f"// Sanad-Tiny full-int8 TFLite model, {len(blob)} bytes. Generated by sanad-ml; do not edit.\n"
        f"alignas(16) const unsigned char g_{name}_data[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"
        f"const unsigned int g_{name}_data_len = {len(blob)};\n"
    )
    h.write_text(
        f"#pragma once\n\nextern const unsigned char g_{name}_data[];\n"
        f"extern const unsigned int g_{name}_data_len;\n"
    )
    return [cc, h]


def write_config_header(
    out_dir: Path,
    q: Int8Model,
    mean: np.ndarray,
    std: np.ndarray,
    trigger_g: float,
    decision_prob: float,
    name: str = "sanad_model",
) -> Path:
    """Everything the firmware needs to prepare input and read the output exactly like training."""

    def arr(v):
        return "{" + ", ".join(f"{float(x):.8g}f" for x in v) + "}"

    decision_q = int(np.clip(np.round(decision_prob / q.out_scale + q.out_zero), -128, 127))
    path = out_dir / f"{name}_config.h"
    path.write_text(f"""#pragma once
// Settings that must match training exactly. Generated by sanad-ml; do not edit.

#define SANAD_FS_HZ            {FS}
#define SANAD_WINDOW_PRE       {PRE}      // samples before the peak (2.5 s)
#define SANAD_WINDOW_POST      {POST}       // samples from the peak on (1.5 s)
#define SANAD_WINDOW_LEN       {PRE + POST}
#define SANAD_PEAK_SEARCH      {int(0.5 * FS)}       // samples after the threshold crossing to find the peak
#define SANAD_ACC_LIMIT_G      {ACC_LIMIT_G:.1f}f    // clip each acc axis before |a| and the model
#define SANAD_TRIGGER_G        {trigger_g:.4f}f // |a| threshold that wakes the model
#define SANAD_DECISION_PROB    {decision_prob:.4f}f // fall if probability >= this
#define SANAD_DECISION_Q       {decision_q}      // same threshold on the int8 output

// Input channels, in order: {", ".join(CHANNELS)} (g, deg/s, Sanad frame)
static const float kSanadMean[{len(mean)}] = {arr(mean)};
static const float kSanadStd[{len(std)}]  = {arr(std)};

// int8 quantization: q = round(x / scale) + zero_point
#define SANAD_IN_SCALE   {q.in_scale:.10g}f
#define SANAD_IN_ZERO    {q.in_zero}
#define SANAD_OUT_SCALE  {q.out_scale:.10g}f
#define SANAD_OUT_ZERO   {q.out_zero}
""")
    return path
